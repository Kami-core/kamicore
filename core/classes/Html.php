declare(strict_types=1);

namespace Core;

if (!defined('IN_KAMI')) die();

final class Html
{
    public static function escape(?string $value): string
    {
        return htmlspecialchars(
            $value ?? '',
            ENT_QUOTES | ENT_SUBSTITUTE,
            'UTF-8'
        );
    }
}
